  static int[][] schedule(byte[] key, int offset, boolean decrypt) {
    int[][] schedule = new int[16][6];
    long v0 = 0, v1 = 0;
    for (int i = 0; i < 4; i++) {
      v0 |= (long) (key[offset + i] & 255) << (i * 8);
      v1 |= (long) (key[offset + i + 4] & 255) << (i * 8);
    }
    long c = 0, d = 0;
    for (int i = 0; i < 28; i++) {
      int b = key_perm_c[i];
      c |= ((b < 32 ? v0 >>> (31 - b) : v1 >>> (63 - b)) & 1) << (31 - i);
      b = key_perm_d[i];
      d |= ((b < 32 ? v0 >>> (31 - b) : v1 >>> (63 - b)) & 1) << (31 - i);
    }
    for (int i = 0; i < 16; i++) {
      int shift = key_rnd_shift[i];
      c = ((c << shift) | (c >>> (28 - shift))) & 0xFFFFFFF0L;
      d = ((d << shift) | (d >>> (28 - shift))) & 0xFFFFFFF0L;
      int row = decrypt ? 15 - i : i;
      for (int j = 0; j < 48; j++) {
        long bit =
            j < 24
                ? (c >>> (31 - key_compression[j])) & 1
                : (d >>> (31 - (key_compression[j] - 27))) & 1;
        schedule[row][j / 8] |= (int) bit << (7 - j % 8);
      }
    }
    return schedule;
  }

  static long[] crypt(long[] input, int[][] key) {
    long[] s = initial(input);
    long s0 = s[0], s1 = s[1];
    for (int i = 0; i < 15; i++) {
      long old = s1;
      s1 = f(s1, key[i]) ^ s0;
      s0 = old;
    }
    s0 = f(s1, key[15]) ^ s0;
    return inverse(s0, s1);
  }

  public static String decrypt(String hex) throws Exception {
    byte[] input = java.util.HexFormat.of().parseHex(hex);
    if (input.length % 8 != 0 || input.length > 2000000)
      throw new IllegalArgumentException("QRC size");
    byte[] key = "!@#)(*$%123ZXC!@!@#)(NHL".getBytes(java.nio.charset.StandardCharsets.US_ASCII);
    int[][][] keys = {schedule(key, 16, true), schedule(key, 8, false), schedule(key, 0, true)};
    byte[] output = new byte[input.length];
    for (int pos = 0; pos < input.length; pos += 8) {
      long[] block = new long[8];
      for (int i = 0; i < 8; i++) block[i] = input[pos + i] & 255;
      for (int[][] k : keys) block = crypt(block, k);
      for (int i = 0; i < 8; i++) output[pos + i] = (byte) block[i];
    }
    return Lyrics.inflate(output);
  }
